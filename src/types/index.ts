export type CapabilityId =
  | '01'
  | '02'
  | '03'
  | '04'
  | '05'
  | '06'
  | '07'
  | '08';

export interface AgentInfo {
  id: string;
  capabilityId: CapabilityId;
  name: string;
  role: string;
  domain: string;
  description: string;
  avatarColor: string;
  accentBg: string;
  accentBorder: string;
  tagline: string;
  systemPrompt: string;
  suggestedPrompts: string[];
  skills: string[];
  voicePitch: number;
  voiceRate: number;
}

export interface RoutingScore {
  agentId: string;
  name: string;
  score: number; // 0 to 100
  reason: string;
  activated: boolean;
}

export interface MoEResult {
  query: string;
  triageAnalysis: string;
  dominantDomain: string;
  routerScores: RoutingScore[];
  activatedAgents: string[];
}

export interface AgentResponseItem {
  agentId: string;
  agentName: string;
  role: string;
  capabilityId: string;
  content: string;
  roundType: 'initial_perspective' | 'critique_counter' | 'synthesis';
  keyInsights?: string[];
  suggestedNextSteps?: string[];
}

export interface ChatMessage {
  id: string;
  role: 'user' | 'assistant' | 'system';
  content: string;
  timestamp: string;
  attachments?: {
    name: string;
    type: string;
    dataUrl: string;
  }[];
  // If generated by MoE / Multi-agent
  routingResult?: MoEResult;
  agentResponses?: AgentResponseItem[];
  synthesis?: {
    executiveSummary: string;
    consensusPoints: string[];
    actionItems: { task: string; ownerAgent: string; priority: 'High' | 'Medium' | 'Low' }[];
  };
  speaker?: {
    id: string;
    name: string;
    role: string;
  };
}

export type ChatMode = 'smoe_swarm' | 'hana_orchestrator' | 'single_agent' | 'project_charter';

export interface ProjectIntakeData {
  clientName: string;
  company: string;
  email: string;
  website?: string;
  primaryCategory: string;
  budgetOrTimeline: string;
  projectBrief: string;
  targetAudience: string;
}
